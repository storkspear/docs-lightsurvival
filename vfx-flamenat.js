/// ⭐ 분출 한 주기 — **확정본 1차 파동의 주기 그대로**(`2π/1.15`). 새 수가 아니다.
const FNPER   = 2*Math.PI/FNW;              // 5.46364초
/// 아무것도 안 나오는 시간(초). ⚠️ 독가스가 1.8초라 **길다**는 판정이 남았다.
const FNHUSH  = .62;
/// 분사 구간 — 주기에서 무음을 뺀 나머지(4.84초 · 주기의 **89%**).
const FNSPRAY = FNPER-FNHUSH;
/// 잦아듦이 차지하는 시간 — 분사 구간의 **뒤 1.15초**.
