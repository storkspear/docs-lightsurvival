const FNTAILLO= .60;
/// ⭐ **팅팅** — `[시작, 길이, 세기]`, 팅팅 구간 안의 자리(0 → 1).
/// 첫 토막은 **잦아들던 분사가 끊기는 것**이고 뒤 셋이 **뽁 · 뽁 · 뽁**이다.
/// ⚠️⚠️ **독가스에서 실측으로 정해진 표다**(`vfx-poison.js` 의 `PZbPOP`) —
///   토막을 다섯으로 쪼갰더니 뒤 둘이 60fps 로 **두 프레임**이라 「뽁」이
///   아니라 **한 번 번쩍**이 됐다. 넷 · 토막 61~76ms · 빈틈 38ms 가 그 답이다.
/// ⚠️ 마지막 토막이 **정확히 1 에서 끝난다**(.84+.16) — 그 뒤로는 아무것도 없다.
const FNPOP   = [[0,.20,1.00],[.30,.18,.60],[.58,.16,.38],[.84,.16,.20]];

/// ⭐⭐ **스케줄 하나** — 압력·길이·세기가 전부 여기서 나온다.
/// ⚠️ `t` 가 음수여도 된다(잔상이 `t−.09` 를 짚는다). 그래서 나머지를 두 번 접는다.
function FNsched(t){
  const u=((t%FNPER)+FNPER)%FNPER;
  const rel=Math.min(1,Math.max(0,(u-(FNSPRAY-FNFADE))/FNFADE));
  const lenK=u<FNSPRAY-FNFADE
    ? FNLMIN+(1-FNLMIN)*FNs3(Math.min(1,u/FNFILL))
    : 1-(1-FNLMIN)*FNs3(rel);
  const P=(lenK-FNLMIN)/(1-FNLMIN);
  let on;
  if(u>=FNSPRAY)on=0;
  else if(rel<FNSPUT)on=Math.min(1,u/FNFILL);
  else{
    const s=(rel-FNSPUT)/(1-FNSPUT);
    on=s<FNPOP[0][1]?FNs3(1-s/FNPOP[0][1]):0;
    for(let k=1;k<FNPOP.length;k++){
      const s0=FNPOP[k][0],du=FNPOP[k][1],pw=FNPOP[k][2];
      if(s>=s0&&s<s0+du){const w=Math.sin(Math.PI*(s-s0)/du);on=Math.max(on,w*w*pw);}}}
  return{u,rel,lenK,P,on,
    ampK:.18+.82*lenK,                       // ② 힘이 없으면 안 휜다
    cool:FNCOOL*(1-P),                       // ④ 불은 꺼진다
    tail:FNTAIL-(FNTAIL-FNTAILLO)*(1-P)};}   // ③ 압력이 죽으면 더 일찍 갈라진다

