//
// ⚠️ **`Math.random` 0건.** ④ 의 떨림은 **확정본 1차 파동의 시간 주파수
//   `1.15 rad/s`([FNW])의 정수배 사인들**에서만 나온다 ⇒ 한 주기
//   `2π/1.15 = 5.4636초`가 정확히 닫혀 **이음매 도약이 0**이다.
//   (이 저장소가 「주기 끝과 처음이 안 맞는」 같은 원인으로 **네 번** 반려당했다.)

// ── ⭐⭐ ① 부력 — **화면의 위**다, 「총구 기준 위」가 아니다 ────────────────
// 실제 화염방사기는 **근원 쪽은 총구 방향으로 곧게** 뻗다가 **끝으로 갈수록
// 위로 말려 올라간다** — 속도가 죽으면 추진력보다 부력이 이기기 때문이다.
//
// ⚠️⚠️ **여기가 제일 틀리기 쉬운 자리다.** 부력을 갈래 좌표계(`nx`·`ny` =
//   `ang` 기준 옆방향)에 얹으면 **아래로 쏠 때 아래로 뜨는** 물건이 된다.
//   ⇒ 그래서 기준을 **화면 세로**(`FNUPX`·`FNUPY` = `(0,−1)`)로 못 박는다.
//   `FCDIR`(조준)이 어디를 보든 힘은 **언제나 화면 위쪽**으로 붙는다.
//
// ── ⚠️⚠️ **「자리를 더하기」가 아니라 「힘을 더하기」다** — 재서 바꿨다 ────
// 처음엔 자리에 바로 더했다(`y −= .18·LEN·u^2.4`, 끝에서 17px). 그런데
// **시안 타일은 `FCDIR = −π/2`(똑바로 위)로 쏜다** — 그러면 부력이 조준축과
// **같은 방향**이라 「말려 오름」이 아니라 **길이 +18%** 가 되고, 실측하니
// 확정본이 **이미 칸 위 끝에 닿아 있어**(위 끝 잘린 화소 평균 5.8 · 최대 23)
// 그 판은 **평균 31.4 · 최대 65 화소가 잘려 나갔다.** 「자연스러워졌다」가
// 아니라 **「왜 잘렸냐」**가 된다.
// ⇒ ⭐ **속도에 더한다**: `dir(u) ∝ 조준 + 화면위·FNBK·u^FNBPOW` 를 **단위로
//   되돌려** 적분한다(중력이 포물선을 만드는 그 식을 거꾸로 세운 것이다). 이러면
//     · 옆으로 쏘면 **말려 올라간다** — 부력 그 자체다
//     · **위로 쏘면 아무 일도 안 일어난다** — 더하는 힘이 조준과 나란해서다.
//       위로 쏜 불은 안 휜다(물리가 그렇다). ⇒ **칸이 한 화소도 더 안 잘린다**
//     · 어느 방향으로 쏘든 **보이는 사거리가 같다**(호 길이 = `LEN` 고정) —
//       조준에 따라 불길이 길어졌다 짧아졌다 하면 그건 그림 버그다
//     · **조준에 대해 연속이다** — 각을 「위쪽으로 돌린다」로 짜면 정확히
//       아래를 지날 때 좌우가 뒤집혀 튄다. 힘으로 짜면 그 자리가 매끈하다
// ⚠️⚠️ **그 대가**: 이 칸은 위로만 쏘므로 **①이 이 그림에서는 안 보인다.**
//   판정용으로 [FNDIR] 을 옆·아래로 돌려 구운 그림을 따로 붙였다.
// ⚠️ `u` 에 대해 **가속하는 곡선**이라야 한다. 선형이면 총구부터 휘어
//   「비스듬히 쏜다」가 된다 ⇒ 지수 [FNBPOW] 는 **2 이상**이다.

/// 매끈한 계단 — 이 파일이 쓰는 **유일한** 완화 곡선이다(양 끝 기울기가 0).
const FNs3 = x => x*x*(3-2*x);

/// **화면 위** 단위벡터 — 캔버스는 `y` 가 아래로 자라므로 위는 `(0,−1)` 이다.
/// ⚠️⚠️ **조준(`FCDIR`)과 무관한 상수**여야 한다. 이 두 줄이 ① 의 정체다.
const FNUPX  = 0, FNUPY = -1;
/// ⭐⭐ **부력 ÷ 추진력** — 끝(`u=1`)에서의 비. 「각을 얼마나 돌린다」가 아니라
/// **힘을 얼마나 더한다**이다: `dir ∝ 조준 + 화면위·FNBK·u^FNBPOW` 를 다시
/// 단위로 만든다. 옆으로 쏠 때 끝 방향이 **36.9° 위로** 꺾이고
/// (실측: 끝이 조준선보다 **19.1px** 위 = 길이의 20.3%) **사거리는 그대로**다.
/// ⚠️⚠️ **1 미만이라야 한다.** 1 을 넘으면 정확히 아래로 쏠 때 흐름이 되돌아
///   오르는데, 그 자리에서 **좌우가 뒤집혀** 조준을 아래로 지나칠 때 그림이
///   튄다. `.75` 면 정확히 아래는 **안 휘고**(부력이 추진을 못 이긴다) 그
///   둘레는 매끈하게 이어진다 — 조준에 대해 **연속**이다.
///   ⇒ 엔진에서 사거리를 크게 늘려 이 값을 1 이상으로 올리게 되면 **그때
///     아래 방향 뒤집힘을 다시 봐야 한다.** 여기 적어 둔다.
const FNBK   = .75;
/// `u` 지수. **2 미만이면 총구부터 휜다.** 실측: `u=.5` 에서 힘의 **19%**,
/// `u=.75` 에서 **49%**, `u=1` 에서 100% — 총구 근처가 사실상 0 이다.
const FNBPOW = 2.40;
/// 호를 적분하는 토막 수. 심프슨이라 48이면 끝점 오차가 1e-9px 밑이다.
const FNARCN = 48;

/// ⭐⭐ **휜 축** — 매 자리의 방향을 「조준 + 화면 위로 커지는 힘」으로 만들고
/// **단위로 되돌린 뒤** 적분한다.
/// ⚠️ **호 길이가 정확히 `LEN`** 이다(단위 방향을 적분한다) ⇒ 어느 조준에서도
///   **보이는 사거리가 같다.** 조준이 화면 위면 더하는 힘이 조준과 나란해
///   방향이 안 바뀌므로 표가 **직선 그대로**다 — 시안 칸이 확정본과 같아진다.
function FNarc(ang,LEN){
  const N=FNARCN,
        X=new Float64Array(N+1),Y=new Float64Array(N+1),
        TX=new Float64Array(N+1),TY=new Float64Array(N+1);
  const ax=Math.cos(ang),ay=Math.sin(ang);
  const dir=v=>{const b=FNBK*Math.pow(v,FNBPOW),
    x=ax+FNUPX*b, y=ay+FNUPY*b, L=Math.hypot(x,y)||1;
    return[x/L,y/L];};
  let x=0,y=0;const d0=dir(0);TX[0]=d0[0];TY[0]=d0[1];
  for(let i=1;i<=N;i++){
    const v0=(i-1)/N,v1=i/N,
          a=dir(v0),m=dir((v0+v1)/2),b=dir(v1);
    x+=LEN/N*(a[0]+4*m[0]+b[0])/6;                 // 심프슨
    y+=LEN/N*(a[1]+4*m[1]+b[1])/6;
    X[i]=x;Y[i]=y;TX[i]=b[0];TY[i]=b[1];}
  return{N,X,Y,TX,TY,LEN};}

/// 휜 축 위의 점과 **단위 접선**. ⚠️ `u>1`(불씨가 끝을 지나간다)이면 끝
///   접선으로 **곧게 이어 간다** — 물지 않으면 표 밖을 읽는다.
function FNat(T,u){
  const N=T.N;
  if(u<=0)return[0,0,T.TX[0],T.TY[0]];
  if(u>=1){const e=(u-1)*T.LEN;
    return[T.X[N]+T.TX[N]*e, T.Y[N]+T.TY[N]*e, T.TX[N],T.TY[N]];}
  const s=u*N,i=s|0,f=s-i;
  const tx=T.TX[i]+(T.TX[i+1]-T.TX[i])*f, ty=T.TY[i]+(T.TY[i+1]-T.TY[i])*f;
  const L=Math.hypot(tx,ty)||1;
  return[T.X[i]+(T.X[i+1]-T.X[i])*f, T.Y[i]+(T.Y[i+1]-T.Y[i])*f, tx/L, ty/L];}

// ── ⭐⭐ ② 난류 — **주파수가 하나뿐이었다** ───────────────────────────────
// 확정본의 좌우 흔들림은 **사인 하나**(`sin(u·π·1.25 − t·1.15)·HL·.33·u^1.6`)라
// 「일정하게 살랑거리는 리본」으로 읽힌다. 실제 유체는 **여러 크기의 소용돌이**가
// 겹친다. ⇒ **작고 빠른 둘째 파동**을 하나 더 얹는다.
// ⚠️⚠️ **첫째 파동은 그대로 둔다** — [PKENV].`ess.lat` 을 **불러서** 쓰고 그
//   위에 더한다(사본을 안 뜬다). 확정본의 「살랑살랑」이 한 항도 안 바뀐다.
// ⚠️ 진폭이 **`u` 와 함께 커져야** 한다 — 근원은 곧고 매끈, 끝은 어지럽게.
//   지수를 1차(1.6)보다 **크게**(2.2) 둬서 총구 쪽이 1차보다도 더 매끈하다.
// ⚠️ 흔들림 **총량**이 커져 「방정맞다」가 되면 안 된다(사용자가 독가스에서
//   그것으로 반려한 적이 있다). ⇒ 진폭을 1차의 **26%** 로만 둔다.

/// 둘째 파동 진폭 — 끝 반폭 `HL` 의 배수. 확정본 1차는 `.33`.
const FNT2A   = .085;
/// 둘째 파동의 **공간** 주파수(`u·π·FNT2K`) — 1차 `1.25` 의 2.64배.
/// 길이를 따라 **1.65 주기**가 들어간다(1차는 0.63주기).
const FNT2K   = 3.30;
/// 둘째 파동의 **시간** 주파수 배수 — 1차([FNW])의 **3배**. ⭐ 정수배라야
/// 한 주기가 닫힌다(④ 와 같은 이유).
const FNT2W   = 3;
/// 둘째 파동의 `u` 지수 — 1차(1.6)보다 커서 **근원이 더 매끈하다**.
const FNT2POW = 2.20;

// ── ⭐⭐ ③ 끝에서 떨어져 나간다 ──────────────────────────────────────────
// 확정본은 **밑판(층 ⓐ `PKfillCool(c,cone(1),…)`)이 끝까지 이어진 한 장**이다.
// 실제 불꽃은 **끝에서 낱낱의 불덩이로 갈라져** 떨어져 나간다.
// ⇒ 밑판이 **끝 26% 구간에서 잦아들어** 덩어리(층 ⓒ [PKfBlobs])만 남게 한다.
//   덩어리는 원래 낱낱이라 **저절로 갈라진다** — 새로 쪼개는 코드가 없다.
//
// ⚠️⚠️ **사용자 규약: 「화염방사는 기본적으로 비어 있는 곳이 있으면 안 됌」.**
//   ⇒ 그래서 **끝 26% 에서만**이다. 몸통(`u < FNTAIL`)은 알파 배수가 **정확히
//   1** 이라 확정본과 한 획도 안 다르다. **몸통에 구멍이 나면 반려된다.**
// ⭐ 덤 — `cone()` 은 `u=1` 에서 좌우를 직선으로 닫아 **평평한 끝**을 만든다.
//   밑판이 거기서 0 이 되므로 그 직선이 애초에 안 그려진다.
// ⭐ 독가스 복제본(`vfx-poison.js` 의 `PZqBomb`)이 **겹침비**로 비슷한 일을
//   하는데, **거긴 성길 때 면을 안 그리는 것**이고 여기는 **끝에서만**이다.
//   거기처럼 `clip` 으로 오려내면 몸통에도 구멍이 뚫린다 — 안 쓴다.

/// 밑판이 **잦아들기 시작하는 자리** — **압력이 꽉 찼을 때.** 끝 **26%** 구간이다
/// (요구는 20~30%).
const FNTAIL  = .74;
/// ⭐⭐ **압력이 죽었을 때**의 같은 자리 — 판이 **더 일찍** 갈라진다.
/// ③과 ⑤를 **한 손잡이(압력)로 묶는** 자리다. 아래 ⑤ 절 참조.
/// ⚠️ 이것은 **끝에서 갈라지는 정도**를 압력이 정한다는 뜻이지, 몸통에 구멍을
///   내는 것이 아니다 — 압력이 0.55 로 죽어도 잦아듦은 `u ≥ .60` 부터다.

// ── ⭐⭐ ④ 근원의 요동 ───────────────────────────────────────────────────
// 실제 노즐은 압력이 미세하게 요동친다. 확정본은 너무 고르다.
// ⇒ **길이**와 **세기**에 아주 작은 떨림. ⚠️ 크면 그건 요동이 아니라
//   **깜빡임**이다 — 그래서 1~3% 다.
// ⚠️⚠️ **`Math.random` 금지.** 결정적 스케줄에서 파생한다. 확정본 1차 파동의
//   시간 주파수 [FNW]=1.15 rad/s 의 **정수배 사인들**만 쓰므로 주기
//   `2π/1.15 = 5.4636초` 가 **정확히** 닫힌다 ⇒ 이음매 도약 0.
