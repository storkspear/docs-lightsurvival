// ① **부력**   끝으로 갈수록 **화면 위**로 말린다.      `u^2.4` · 힘 비 `.75`
// ② **난류**   작고 빠른 **둘째 파동**을 얹는다.        `u^2.2` · `.085·HL`
// ③ **끝에서 갈라짐** 밑판이 끝 26% 에서 잦아든다.      `u ≥ .74`
// ④ **근원의 요동**  길이·세기가 아주 조금 떨린다.      ±1.4% · 2.6%p-p
// ⑤ **분출 · 사그라듦** 길이가 줄고 마지막에 **팅팅**.  주기 `2π/1.15` = 5.46초
