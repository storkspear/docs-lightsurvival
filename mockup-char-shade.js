// ── 캐릭터 장 「암 影」(특수) — **여섯 장과 같은 틀, 다른 처지** ────────────
//
// ⭐⭐ 틀은 `char-page.js` 가 쥔다(그리기 · 격자 · 띠 · 자물쇠 · 빈 칸 · 가드 ·
//   결계 줄). 기본 여섯 장이 쓰는 그 틀을 **한 줄도 안 고치고** 그대로 쓴다 —
//   특수 장을 위해 [charDeck] 을 손보면 여섯 장이 같이 흔들린다. 다른 점은
//   전부 **인자**로 낸다(`bands` · `why` · 색).
//
// ⚠️⚠️ **`vfx.js` · `char-page.js` 뒤에 실린다.** 이름을 `CS_` 로 격리한다 —
//   48,000줄 뒤에 실리는 파일이라 최상위 `const` 가 하나만 겹쳐도 **스크립트가
//   통째로 죽는다**(2026-08-22 확인: `CS_*` 가 vfx/chapter/nav/rock/char-page 에서
//   0건, 호스트 `csbody`·`csskill` 도 0건).
//
// ⭐⭐ **왜 이 장이 있나.** 2026-08-22 판정으로 **결계가 「입히는 것」이 아니라
//   속성마다 제 방어 스킬**이 됐다(사용자 원문: 「결계 방어를 결계가 입힌다는
//   느낌이 아니라 **아예 속성의 방어 스킬로 편입**」). 그 여덟 중 둘이 특수
//   속성의 것이고 갈 곳이 없으면 **판정과 함께 스킬이 사라진다.**
//   ⇒ 이 장은 **보관소**다. 엔진 배선은 안 한다 — 사용자 판정: 「**특수는
//     어차피 새로 만들 거야 신경 안 써도 돼**」(원장 =
//     `docs/design/속성-개선-백로그.md` 「방어 계열 판정」).
//
// ⚠️⚠️ **암 影 은 쌍이 아니다.** 특수 열 종은 여섯 속성의 쌍(`FVNAME`)인데
//   암은 그 표에 없고 `ELEMS` 에 **제 몸과 제 둘레 모티프**로 서 있는 **일곱째 속성**이다.
//   그래서 이 장은 폭마 장과 달리 [charBody] 를 **쓸 수 있다.**
// ⚠️ **이름이 두 갈래다** — `ELEMS` 는 「어둠 影」, 원장과 `WLTBL` 은 「암 影」.
//   이 장은 **원장을 따랐다**. 새 이름을 지은 것이 아니라 **둘 중 하나를 고른
//   것**이고, 갈라짐 자체는 남아 있다(판정 대기).

// ── 몸 — `ELEMS` 목록에서 캡션까지 읽어 온다 ──────────────────────────────
charBody("csbody", ["preShade", "shade"]);

// ── 열두 칸 ───────────────────────────────────────────────────────────────
//
// ⚠️ 두 줄 다 **손으로 안 적는다.**
//   · 결계 — [charWard] 가 `WLTBL`/`WLtxt` 에서 이름·부제·다섯 줄을 읽는다.
//   · 암전 — `MGDEF`(계열 격자 캡션 = L1) + `MGLVT`(L2~L5). `MGLVT` 는
//     **L2 부터**라는 계약이라 앞에 한 칸을 끼워야 「칸마다 한 줄」이 된다.
// ⚠️ 칸 키가 엔진 id 와 다르다: 엔진 `dusk` ↔ 시안 `MGFX.mgNovaDusk`(창작 마법
//   열 종은 `tile` 의 물들임 규약 때문에 `FX` 밖에 산다). 그래서 아래 `reg` 에
//   `MGFX` 를 얹는다 — 안 얹으면 그 줄이 **조용히** 사라진다.
// ⭐ 등급·계열은 안 바뀐다 — 암전은 `SKTAG` 기준 **마법 · 오라**다.
const CS_DUSK = (() => {
  if (typeof MGDEF === "undefined" || typeof MGLVT === "undefined") return null;
  const w = MGDEF.find((x) => x[0] === "mgNovaDusk");
  if (!w) { console.warn("암 — MGDEF 에 mgNovaDusk 가 없다"); return null; }
  const l1 = (typeof MGLVT1 !== "undefined" && MGLVT1.mgNovaDusk) || w[3];
  return ["mgNovaDusk", "암전 暗轉", charRk("마법", "變 변주"),
    [l1].concat(MGLVT.mgNovaDusk || [])];
})();

const CS_NOW = [CS_DUSK, charWard("WLwardShade")].filter(Boolean);

// ⚠️ **비어 있다.** 둘뿐이라 뒤 띠 아래는 통째로 자물쇠다.
const CS_LATER = [];

// ⚠️⚠️ **띠 문구가 기본 여섯 장과 다르다.** 거기서는 「즉시 여섯 / 추가 여섯」이
//   **캐릭터를 사면 열리는 것 ↔ 상점 추가 구매·숙련도 해금**을 가르는데, 특수
//   속성은 **캐릭터 자체가 아직 없다** — 열두 칸을 가를 선을 그을 자리가 아니다.
//   ⇒ [charDeck] 의 `bands` 인자로 이 장만 갈아 끼운다(틀은 안 고친다).
charDeck({
  host: "csskill", label: "암(특수)", color: "#6B4E8C", name: "CScell",
  reg: charReg(MGFX, WLFX),
  now: CS_NOW, later: CS_LATER,
  bands: [
    ["살려 둔 두 칸", "암전과 결계 · 암 影 — 갈 곳이 없으면 판정과 함께 사라진다"],
    ["나머지", "특수 속성은 <b>출시 범위 밖</b>이라 아직 한 칸도 안 정해졌다"],
  ],
  why: "다만 <b>지금 채울 차례가 아니다</b> — 특수 속성은 " +
    "<b>출시 범위 밖</b>이고 <b>상점 해금 대상</b>이라, 기본 여섯의 빈 칸을 " +
    "다 메운 뒤에 오는 일이다(사용자: 「특수는 어차피 새로 만들 거야」). " +
    "이 장이 지금 하는 일은 <b>두 종을 잃지 않게 보관하는 것</b> 하나다.",
});
