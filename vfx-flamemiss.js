// ── ④ ⭐⭐ 되풀이 방지 — **적 0마리 슬롯을 못 박는다** ──────────────────────
// 이 병의 뿌리는 「시연 칸이 가짜 적을 늘 세워 두는 것」이었다. 그래서 칸 ③은
// **영구히 빈 마당**이다([FLMFOE] 의 셋째 줄이 `null`).
// ⚠️ **여기에 적을 세우지 마라 — 세우는 순간 이 파일이 존재하는 이유가 없어진다.**
