// 엔진 계약이 「**보이는 것 = 맞는 것**」이라 그 구간에는 판정이 아예 안 돈다
// (`flamer_tuning.dart` 의 `kFlamerOnGate`). 그래서 이 칸들은 **만렙이 아니라
