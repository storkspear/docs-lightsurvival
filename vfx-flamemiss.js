/// 어느 칸으로 그리나 — **L3**. 머리말 ⑤ 참조(만렙은 무음이 없어 못 보인다).
const FLMLV = 3;

/// 적이 서는 자리 · 크기 — `[가로, 세로, 반지름]`(총구 기준 · 238 눈금).
/// 셋째 줄의 **`null` 은 「적 0마리」**다(머리말 ④). 여기에 적을 세우지 마라.
///
/// ① 은 **부채 한복판인데 사거리 밖**이다: L3 길이 112 인데 세로 −150 에 세운다
///   (`FLXsim` 의 판정은 `d < LEN·lenK + f.r` 이라 반지름 11 을 더해도 못 닿는다).
/// ② 는 **부채 안**(세로 −74)이라 뿜는 동안 계속 탄다 — 그러다 사라진다.
const FLMFOE = [
  [0, -150, 11],
  [0, -74, 11],
  null,
];

/// 적이 사라지는 자리 — **분사 구간의 몇 몫에서**인가(칸 ② 전용).
/// ⚠️ 절대 시각이 아니라 **몫**이라 무음이 다른 칸으로 옮겨도 자리가 안 밀린다.
const FLMDIE = .55;

/// 사라지는 데 걸리는 시간(초) · 흩어지는 조각 수 · 조각 수명(초) · 속도.
const FLMFADE = .26, FLMDN = 9, FLMDL = .38, FLMDV = 62;

/// 그 칸의 마당을 한 번만 세운다 — [mgInit] 은 `st.F` 가 있으면 손을 안 댄다.
/// ⚠️ `st.F` 를 **빈 배열**로 둬도 안전하다(빈 배열은 참이라 [mgInit] 이 안 덮는다).
function FLMfield(st, SC, spec) {
  if (!st.FLMall) st.FLMall = spec ? mkFoes([[spec[0] * SC, spec[1] * SC, spec[2] * SC]]) : [];
  return st.FLMall;
}

/// 칸 ② — 적이 **사라지는 몫**(1 = 멀쩡 · 0 = 없다). 확정본 주기에서 파생된다.
function FLMalive(t, hush) {
  const u = ((t % FLXPER) + FLXPER) % FLXPER;
  const die = (FLXPER - hush) * FLMDIE;
  if (u < die) return 1;
  const w = (u - die) / FLMFADE;
  return w >= 1 ? 0 : 1 - w;
}

/// 사라지는 적의 **조각** — 「없어졌다」를 알파가 아니라 **개수**로 낸다.
///
/// ⚠️⚠️ 알파만 내리는 안은 서리결정에서 반려됐다: 옅어지는 동안 물건이 **그
///   자리에 그대로 떠 있어** 「굳어져 있음」과 화면에서 구별이 안 된다.
///   여기서도 같은 판정을 그대로 따른다.
function FLMdust(c, cx, cy, f, w, SC) {
  const x = cx + f.ox + f.kx, y = cy + f.oy + f.ky;
  for (let i = 0; i < FLMDN; i++) {
    const a = i / FLMDN * TAU + f.ox * .01;
    const q = w * FLMFADE / FLMDL;
    if (q >= 1) continue;
    const d = FLMDV * SC * q * (.6 + .8 * hash(i * 3.1));
    const r = f.r * (.20 + .16 * hash(i * 5.7)) * (1 - q);
    if (r <= .4) continue;
    fillPoly(c, PKrag(x + Math.cos(a) * d, y + Math.sin(a) * d + FLMDV * SC * q * q * .35,
      r, i * 2.3, 7, .34, a), A("#16101C", .92 * (1 - q)));
  }
}

/// **칸 하나** — 확정본 [FLXdraw] 를 그대로 부르고 **마당만** 갈아 끼운다.
///
/// ⚠️ 그리기 순서가 확정본 그대로라야 한다: 마당을 먼저 세우고([FLMfield]),
///   확정본이 그 마당을 보며 판정·표식·불을 그린다. 조각만 **뒤에** 얹는다
///   (적이 있던 자리라 불보다 앞이다).
function FLMcell(c, t, dt, W, H, st, slot) {
  const SC = Math.min(W, H) / 238;
  const spec = FLMFOE[slot];
  const all = FLMfield(st, SC, spec);
  const hush = FLXhush(FLMLV - 1);
  // 칸 ② 만 사라진다. 나머지 둘은 마당이 안 바뀐다.
  const alive = slot === 1 ? FLMalive(t, hush) : 1;
  st.F = alive > 0 ? all : [];
  const sl = LV;
  LV = FLMLV;
  try {
    FLXdraw(c, t, dt, W, H, st, FLXLV[FLMLV - 1], FLXCY, FLXCOLLV[FLMLV - 1]);
  } finally {
    LV = sl;
  }
  if (slot === 1 && alive > 0 && alive < 1) {
    FLMdust(c, W / 2, H * FLXCY, all[0], 1 - alive, SC);
  }
}

