// 사슬·독침과 갈리는 자리다. 저 둘은 **표적을 보고** 자리를 정하므로 표적이
// 없으면 그릴 자리가 없어지지만, 불은 **표적을 안 본다** — 총구가 정한 방향으로
// 정한 거리만큼 뿜고, 그 앞에 무엇이 있든 없든 그림이 한 획도 안 바뀐다.
// ⇒ **여기에 「빗나감 연출」을 만들면 안 된다.** 불이 표적을 못 찾아 흔들리거나
//   짧아지거나 색이 바뀌면, 그것은 「불」이 아니라 「유도무기」의 문법이다.
//   이 파일이 하는 일은 **그 사실을 그림으로 못 박아** 다음 사람이 없는 연출을
//   지어내지 않게 하는 것이다.
//
// ⭐ 대신 진짜로 갈리는 것이 **하나** 있고, 그것만 이 칸들이 보인다:
//   **점화 표식**(`mgBurn`)과 **넉백**(`hitFoe`)은 맞은 적에게만 생긴다. 아무도
//   없으면 그 층이 통째로 없다 — 「불은 그대로, 표식만 없다」가 이 무기의 빗나감이다.
