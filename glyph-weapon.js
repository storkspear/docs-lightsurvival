/// 도감 문양의 두 톤. 부르는 장이 제 색을 넘기면 그것이 이긴다.
const WGFRONT = "#E8F8FF", WGBACK = "#4E7A96";

/// 위가 밝고 아래가 어두운 칠 한 겹. **섞이는 띠를 짧게**(0.44→0.60) 둬서
/// 「깎인 면」으로 읽히게 한다 — 한 줄로 뚝 자르면 스티커가 된다.
function wgTone(c, W, fr, bk) {
  const g = c.createLinearGradient(0, 0, 0, W);
  g.addColorStop(0, fr || WGFRONT);
  g.addColorStop(0.44, fr || WGFRONT);
  g.addColorStop(0.60, bk || WGBACK);
  g.addColorStop(1, bk || WGBACK);
  return g;
}

/// 점 목록 하나를 닫아 칠한다. 좌표는 **0~1** 이고 `W` 가 곱해진다.
function wgPoly(c, W, pts) {
  c.beginPath();
  for (let i = 0; i < pts.length; i++) {
    const x = pts[i][0] * W, y = pts[i][1] * W;
    i ? c.lineTo(x, y) : c.moveTo(x, y);
  }
  c.closePath(); c.fill();
}

/// **깎인 뒤 · 뾰족한 앞**의 조각 하나 — 이 일곱의 기본 획이다.
/// `(cx,cy)` 에서 각 `an` 으로 `r0`→`r1`, 두께 `th`.
/// ⚠️ **둥근 끝을 한 자리도 안 쓴다.** 첫 판이 둥근 막대였는데 20px 에서
///   「목록 아이콘」으로 읽혔다(2026-08-27 실측) — 이 게임의 결은 셀 셰이딩의
///   각진 면이라 끝이 둥글면 그 순간 UI 부품이 된다. 뒤를 깎고 앞을 물린다.
function wgSlab(c, W, cx, cy, an, r0, r1, th, noseK) {
  const ux = Math.cos(an), uy = Math.sin(an), px = -uy, py = ux;
  const h = th / 2, n = h * (noseK == null ? 1.25 : noseK), k = h * 0.46;
  const P = (s, t) => [cx + ux * s + px * t, cy + uy * s + py * t];
  wgPoly(c, W, [P(r0 + k, -h), P(r1 - n, -h), P(r1, 0), P(r1 - n, h),
                P(r0 + k, h), P(r0, h - k), P(r0, -h + k)]);
}

/// 밑동이 넓고 끝이 뾰족한 **각진 이빨** 하나 — 갈래가 쓴다.
/// ⚠️ 어깨(`r1 - hw*1.5`)에서 한 번 꺾인다. 밑동에서 끝까지 곧게 좁히면 아무리
///   굵게 잡아도 **바늘**이 되고, 다섯을 세우면 그 순간 풀밭으로 읽힌다
///   (2026-08-27 실측). 꺾인 어깨가 있어야 「깎인 돌」이 된다.
function wgWedge(c, W, cx, cy, an, r0, r1, hw) {
  const ux = Math.cos(an), uy = Math.sin(an), px = -uy, py = ux;
  const P = (s, t) => [cx + ux * s + px * t, cy + uy * s + py * t];
  const sh = Math.max(r0 + (r1 - r0) * 0.35, r1 - hw * 1.5);
  wgPoly(c, W, [P(r1, 0), P(sh, hw * 0.62), P(r0, hw),
                P(r0, -hw), P(sh, -hw * 0.62)]);
}

/// 굽은 띠 하나 — 바깥 호와 안쪽 호 사이를 채운 **면**이다(획이 아니다).
/// `taper` 가 1 이면 양 끝에서 두께가 0 으로 잦아든다(초승달), 0 이면 고른 띠다.
function wgArcBand(c, W, cx, cy, r, th, a0, a1, taper) {
  const N = 26, out = [], inn = [];
  for (let i = 0; i <= N; i++) {
    const u = i / N, an = a0 + (a1 - a0) * u;
    // 끝으로 갈수록 얇아지는 몫 — `cos` 반주기라 양 끝이 매끄럽게 맺힌다.
    const k = taper ? Math.pow(Math.cos((u - 0.5) * Math.PI), 0.55) : 1;
    const t = th * (taper ? k * 0.96 + 0.04 : 1);
    const co = Math.cos(an), si = Math.sin(an);
    out.push([cx + co * (r + t / 2), cy + si * (r + t / 2)]);
    inn.push([cx + co * (r - t / 2), cy + si * (r - t / 2)]);
  }
  wgPoly(c, W, out.concat(inn.reverse()));
}

/// 두 점을 잇는 **굽은 윤곽 한 도막**(2차 베지에) — 가운데를 진행 방향의 법선으로
/// `bow` 만큼 민다. 위에서 아래로 훑을 때 양수가 **바깥**(오른쪽)이다.
/// ⚠️ 획이 아니라 **면의 테두리**다 — 이 파일은 `stroke` 를 한 자리도 안 쓴다.
function wgBow(pts, a, b, bow, n) {
  const dx = b[0] - a[0], dy = b[1] - a[1], L = Math.hypot(dx, dy) || 1;
  const cx = (a[0] + b[0]) / 2 + (dy / L) * bow;
  const cy = (a[1] + b[1]) / 2 - (dx / L) * bow;
  const m = bow ? (n || 6) : 1;
  for (let i = 1; i <= m; i++) {
    const u = i / m, v = 1 - u;
    pts.push([v * v * a[0] + 2 * v * u * cx + u * u * b[0],
              v * v * a[1] + 2 * v * u * cy + u * u * b[1]]);
  }
}

/// 화염방사의 몸 — **밑동이 뭉툭한 통짜 면 하나**이고, 앞 모서리만 혀로 맺는다.
/// 후보 넷이 이 함수 하나를 쓰고 **표만 다르다** — 몸(밑동 · 통짜 · 앞으로 쏠린
/// 무게)이 넷 다 같아야 「얹은 정도」만 견줄 수 있다.
///   `o.T`    혀 목록 `[골, 끝, 윗 모서리 휨, 아랫 모서리 휨]` — 골은 그 혀 **앞**의
///            파인 자리다. 휨의 양수는 **위에서 아래로 훑을 때 바깥**이다.
///   `o.foot` 마지막 혀가 내려앉는 아래 앞 모서리
///   `o.top`  몸 윗선의 휨 · `o.bot` 몸 아랫선의 휨
function wgFlameBody(c, W, o) {
  const RX = 0.02, RH = 0.235, RK = 0.075;         // 밑동 — 뭉툭하게 깎는다
  const top = [RX + RK, 0.50 - RH], bot = [RX + RK, 0.50 + RH];
  const pts = [top];
  wgBow(pts, top, o.T[0][0], o.top);
  for (let i = 0; i < o.T.length; i++) {
    const [v, t, bu, bl] = o.T[i];
    wgBow(pts, v, t, bu);                          // 혀의 윗 모서리
    wgBow(pts, t, i + 1 < o.T.length ? o.T[i + 1][0] : o.foot, bl);   // 아랫 모서리
  }
  wgBow(pts, o.foot, bot, o.bot);
  pts.push([RX, 0.50 + RH - RK], [RX, 0.50 - RH + RK]);
  wgPoly(c, W, pts);
}

