// ⭐ **연쇄 한 마리의 스케줄** — 1차와 **같은 모양, 2/3 길이**
// ══════════════════════════════════════════════════════════════════════════
// ⚠️ 완화 곡선([ZNs3])도 오름 비율([ZNZA]·[ZNPA]·[ZNBA]·[ZNFA]·[ZNIGN]·[ZNHOLD])도
//   **1차 것을 그대로** 쓴다 — 새 곡선을 지으면 두 파동이 다른 물건으로 보인다.
//   갈리는 것은 **길이(2/3)** 와 **시작 시각(t0)** 뿐이다.
// ⚠️⚠️ **각 채널이 제 창의 양 끝에서 정확히 0** 이라, 창 밖에서는 값이 없는 게
//   아니라 **0 으로 이어진다.** 그래서 이음매(`u=0`)에서 전부 0 이다.
function ZNcsched(u,t0){
  const T1=t0+ZNCZAP, T2c=T1+ZNCFUSE, T3c=T2c+ZNCBURN;
  // ── 전기 — ① 줄기와 **같은 곡선**, 2/3 수명
  let zap=0;
  if(u>=t0&&u<T1){const v=(u-t0)/ZNCZAP;
    zap = v<ZNZA ? ZNs3(v/ZNZA) : 1-ZNs3((v-ZNZA)/(1-ZNZA));}
  // ── 겹 셋 — **수는 그대로**(삑 삑 삑), 간격만 2/3
  const pop=[0,0,0], fill=[0,0,0];
  for(let i=0;i<ZNCAP;i++){
    const at=T1+ZNCSTK*(i+1);
    if(u>=at)fill[i]=ZNs3(Math.min(1,(u-at)/ZNFA));
    const d=u-at;
    if(d>=0&&d<ZNPOP){const v=d/ZNPOP;
      pop[i]= v<ZNPA ? ZNs3(v/ZNPA) : 1-ZNs3((v-ZNPA)/(1-ZNPA));}}
  let pip=0;
  const PX=ZNPIPX*ZNC23;                     // 칸이 걷히는 시간도 2/3
  if(u>=T1&&u<T2c)          pip=ZNs3(ZNcl((u-T1)/ZNPIPF));
  else if(u>=T2c&&u<T2c+PX) pip=1-ZNs3((u-T2c)/PX);
  // ── 펑 — 1차와 같은 곡선, 2/3 수명. **범위만 1/2**([ZNCHALF], 그리는 쪽에서)
  let boom=0;
  if(u>=T2c&&u<T2c+ZNCBOOM){const v=(u-T2c)/ZNCBOOM;
    boom = v<ZNBA ? ZNs3(v/ZNBA) : 1-ZNs3((v-ZNBA)/(1-ZNBA));}
  // ── 자염 — 압력 `P` 와 세기 `on`. 1차와 **같은 봉투**, 2/3 길이·2/3 크기
  let P=0,on=0,decay=0;
  if(u>=T2c&&u<T3c){const v=(u-T2c)/ZNCBURN;
    P  = v<ZNIGN ? ZNs3(v/ZNIGN) : 1-ZNs3((v-ZNIGN)/(1-ZNIGN));
    decay = v<ZNIGN ? 0 : ZNs3((v-ZNIGN)/(1-ZNIGN));
    on = v<ZNIGN ? ZNs3(v/ZNIGN)
       : (v<ZNHOLD ? 1 : 1-ZNs3((v-ZNHOLD)/(1-ZNHOLD)));}
  // ── 재 — ⚠️⚠️ **2차에는 「여운 자리」가 없다.** 제일 늦게 터지는 것은 자염이
  //   [ZNEND] 에서 **정확히** 끝나므로 그 뒤에 재가 남을 시간이 0 이다.
  //   ⇒ 1차처럼 「불 → 여운」 두 창으로 못 가른다. **한 창으로 종을 친다** —
  //     `[T2c, ZNEND]` 안에서 오르고 내려 **양 끝에서 정확히 0** 이다.
  let soot=0;
  if(u>=T2c&&u<ZNEND){const w=(u-T2c)/Math.max(1e-6,ZNEND-T2c);
    soot=ZNs3(Math.min(1,w/ZNSOOTF))*(1-ZNs3(w));}
  return{u,zap,pop,fill,pip,boom,P,on,decay,soot,
    // ⭐ 2차 불기둥의 배율 — 1차의 상수 배율에 **2/3** 을 곱한 것뿐이다.
    plumeK:ZNKF*ZNC23,
    // 꺼짐 — 1차와 **같은 넷**이 같은 손잡이에서 나온다.
    cut:decay, rise:ZNRISE*decay, spread:1+ZNSPRD*decay, grow:1+ZNGROW*decay,
    cool:ZNCOOL*decay,
    // 1차 스케줄과 **같은 열쇠**를 갖게 채운다 — 그리는 함수를 그대로 부르려면
    // 모양이 같아야 한다(0 이라 아무것도 안 그린다).
    kn:0, emb:0, mk:0, stk:0, at:[0,0,0], tq:0, th:0};
}
/// 연쇄가 그 적을 얼마나 「맞았다」로 만드나 — **1차와 같은 규칙**이다.
