// ⚠️ 최상위 이름을 전부 `ZN` 으로 격리한다 — 실측으로 **0건** 확인:
//   vfx / nav / char-page / chapter / rock / progress-data /
//   vfx-poison / vfx-flamelv / vfx-flamenat / vfx-frostspot / vfx-frostlv.
//
// ⚠️ **옛 마 타일은 안 건드렸다.** `vfx-poison.js` 의 `PZnumbA`·`PZnumbB`·
//   `PZnumbHalt` 는 독가스 담당 것이라 **한 글자도 안 봤다**(읽기만).
//   새 것이 서면 그쪽에서 정리할 자리다.
//
// ── ⚠️ 게이트가 이 파일을 안 돈다 (실측) ──────────────────────────────────
// `tools/mockup_lint.js` 의 런타임 하네스(`runtimeCounts`)와
// `tools/mockup_smoke.js` 는 **둘 다 `docs/vfx/vfx.js` 하나만** 읽는다.
// ⇒ 자체 검증은 합본으로 돈다:
//   `cat docs/vfx/vfx.js docs/vfx/vfx-numb.js > /tmp/zn.js &&
//    node tools/mockup_smoke.js /tmp/zn.js`
// ⇒ 그리고 린트 ⑪(제목의 「N종」 ↔ 실제 칸 수)이 이 파일의 칸을 **0으로** 세므로
//   새 `<h2>` 에는 **「N종」을 안 쓴다**.
//
// ── ⚠️ **난수 0** ────────────────────────────────────────────────────────
// `Math.random`·`R()` 을 **한 번도 안 쓴다.** 들쭉날쭉은 전부 `vfx.js` 의
// [hash] 표에서 나오고, **그려지는 값 전부가 시각 `t` 의 순함수**다 —
// 적분되는 상태가 하나도 없다([stepFoes]·[hitFoe]·[emit]·[stepP] 를 안 쓴다).
// ⇒ 같은 `t` 를 두 번 그리면 픽셀이 같다.
// ⚠️ 이 저장소가 「주기 끝과 처음이 안 맞는」 같은 원인으로 **네 번** 반려당했다.
//   그래서 **스케줄이 하나**([ZNsched])이고 그리는 값이 전부 거기서 파생된다.
