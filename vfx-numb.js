//   「짧다」와 같이 가야 팍 하고 꽂힌 것으로 읽힌다.
const ZNZAMP=13, ZNZN=5, ZNZW=8.0;
/// 굵기 곡선 — 가운데가 굵고 양 끝이 가늘다. 던져진 것의 몸통이다.
const ZNzProf=v=>.34+.66*Math.sin(Math.PI*ZNcl(v*1.04+.02));
function ZNzap(c,S,cx,cy,tx,ty,SC){
  if(!(S.zap>0))return;
  const a=S.zap;
  // ⚠️ 씨앗이 **사건 하나에 고정**이다(시간을 안 탄다) — 뇌광의 지글거림과
  //   여기서 갈린다. 그리고 한 주기 안에서 모양이 안 변하니 이음매도 없다.
  const P=PKjag(0,0,[cx,cy],[tx,ty],11.3,ZNZAMP*SC,ZNZN);
  ZNwithTone(ZNK,ZNVIOL,()=>{
    gAdd(c,g=>{
      // ⚠️ 폭이 **알파를 따라 조여야** 한다. 앞 판은 `.55+.45·a` 라 꺼질 때
      //   심이 먼저 죽고 윤곽 둘만 남아 **가는 실 두 줄**로 보였다 — 이 레포가
      //   「거미줄」로 반려하는 바로 그 모양이다. 폭을 조이면 두 윤곽이 만나
      //   **한 줄로 오므라들며** 사라진다.
      PKboltThick(g,P,ZNZW*SC*(.18+.82*a),ZNK,a,11.3,ZNzProf);
      // 총구 — 몸에서 나가는 자리. 작고 밝게.
      gFlare(g,cx,cy,7.5*SC*a,ZNK,a*.9,Math.atan2(ty-cy,tx-cx),4);
      // 꽂힌 자리 — **여기서 겹이 시작된다**는 표시다.
      gFlare(g,tx,ty,9.5*SC*a,ZNK,a,Math.atan2(ty-cy,tx-cx)+.7,6);});});
}

