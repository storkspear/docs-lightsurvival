// ⚠️ 그래서 **사본 넷을 지웠다** — `ZNblobs`(=[PKfBlobs] 사본) · `ZNENV`
//   (=[PKENV].`ess` 사본) · `ZNcoolRamp`(제 색 사다리) · `ZNfade`(제 밑판 닫기).
//   사본을 두면 확정본이 바뀔 때 갈라진다.
// ⚠️ 3단 계조가 필요한 나머지 자리([gStroke]/[gHalo] 는 `TONE` 키를 받는다)는
//   여전히 **새 색을 안 만든다** — 배합에 **이미 있는 세 값**을 꽂는다:
