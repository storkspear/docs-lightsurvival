// ② **겹** — 기폭의 문법 그대로                              「삑 · 삑 · 삑」
// ══════════════════════════════════════════════════════════════════════════
// ⭐ **[MGFX.mgNovaDetonate] 에서 그대로 빌린 것 넷**:
//   ⓐ **부채로 늘어놓는다** — 폭 `SPAN=3.6rad` 고정, 간격은 상한에서 파생
//      (`GAP=min(.5, SPAN/(CAP−1))`), 알갱이 크기도 상한에서 파생
//      (`PIP=min(1,max(.62,5.5/CAP))`).
//   ⓑ **적 몸에 붙는다** — 반지름 `f.r + 15·SC`. 화면 아무 데나 뜨면 누가
//      터지는지 모른다.
//   ⓒ ⭐⭐ **빈 칸도 그린다** — 켜진 것 `4.6·PIP·SC` 알파 `.95`,
//      빈 것 `2.6·PIP·SC` 알파 `.28`. 「상한이 화면에 있어야 **지금 덜 쌓인
//      것**과 **상한이 낮은 것**이 갈린다」(2026-08-11 렌더 판정).
//   ⓓ **알갱이 문법** — [celSplash] 각 5, 씨앗 `i*3+2`.
// ⚠️ 다른 것 하나: 겹이 **앉는 순간 한 번 부푼다**(팝). 원본은 그냥 켜지는데,
//   사용자가 요구한 것이 「**삑** 하면서」라는 **사건**이라 그 순간이 보여야 한다.
//   ⚠️ 되풀이되는 온·오프가 **아니다** — 겹마다 딱 한 번, 30ms 에 부풀어
//     0.30초에 걸쳐 가라앉는다. 반복 점멸(독가스가 반려당한 것)과 다르다.
const ZNSPAN=3.6;
function ZNstack(c,S,x,y,r,SC){
  const A0=S.pip; if(!(A0>0))return;
  const CAP=ZNCAP;
  const GAP=CAP>1?Math.min(.5,ZNSPAN/(CAP-1)):0;
  const PIP=Math.min(1,Math.max(.62,5.5/CAP));
  for(let i=0;i<CAP;i++){
    const a=-Math.PI/2+(i-(CAP-1)/2)*GAP;
    const px=x+Math.cos(a)*(r+15*SC), py=y+Math.sin(a)*(r+15*SC);
    const f=S.fill[i], p=S.pop[i];
    // ⓐ **빈 칸 — 늘 그린다.** 상한이 화면에 있어야 「지금 덜 쌓인 것」과
    //    「상한이 낮은 것」이 갈린다(원본이 못 박은 규약).
    celSplash(c,px,py,2.6*PIP*SC,5,i*3+2,"numb",.28*A0);
    // ⓑ **앉은 겹 — 빈 칸 위에 겹쳐 자란다.** 켜고 끄면 그것이 곧 도약이다
    //    ⇒ 크기도 알파도 [ZNFA](30ms) 에 걸쳐 오른다.
    if(f>0)celSplash(c,px,py,(2.6+2.0*f)*PIP*SC*(1+1.05*p),5,i*3+2,"numb",.95*f*A0);
    // ⓒ **팝** — 앉는 순간 딱 한 번. 되풀이되는 온·오프가 아니다.
    if(p>0)gAdd(c,g=>gHalo(g,px,py,11*PIP*SC*(.5+p),"numb",.55*p*A0));}
}

