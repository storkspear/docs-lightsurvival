//   뇌광 `TONE.mArc` 몸통 `#9B6BFF` = **H 259.5° S 100% L 71%**
//   자염 `PKT.violet`      `#D93AC8` = **H 306.4° S  68% L 54%**
//   ⇒ **색상 Δ 47.0°** · 채도 Δ 32%p · 명도 Δ 17%p.
//   30° 가 「나란히 놓았을 때 갈리는 최소치」라는 것이 이 레포의 팔레트 규약
//   (`TONE.volt` 주석)이므로 **47° 는 그 최소치를 넘는다.** 다만 광주
//   `#C89BFF`(267.0°)와는 39.4° 라 **뇌 계열 전체와는 그만큼만 떨어져 있다** —
//   보라 대역이 이미 붐빈다는 사실은 그대로 남는다. ⇒ 임의로 색을 안 바꿨다.
//   ⚠️ 그래서 **모양·수명으로 더 갈랐다** — 아래 [ZNzap] 머리말 참조.
//
// ── ⚠️ 왜 별도 파일인가 ──────────────────────────────────────────────────
// `vfx.js` 는 **50,761줄**이고 같은 날 그 파일에서 정규식 하나가 31,000줄을
// 날렸다. 이 사이클에 다른 손 넷이 `vfx-poison.js`·`vfx-flamelv.js`·
