/// 매끈한 계단 — 이 파일이 쓰는 **유일한** 완화 곡선이다(양 끝 기울기 0).
const ZNs3 = x => x*x*(3-2*x);
/// 0~1 로 물린다.
const ZNcl = x => x<0?0:(x>1?1:x);

// ── ⭐⭐ 주기 — **새로 안 지었다** ────────────────────────────────────────
// 화염방사 확정본의 1차 파동([PKENV].`ess.lat`)의 시간항이 `t·1.15` 이므로 그
// 파동의 주기가 `2π/1.15 = 5.46364초`다. ④ 의 자염이 **그 파동을 그대로 타므로**
// 분출 주기를 거기에 못 박으면 얹은 것 전부가 **한 주기에서 정확히 닫힌다.**
// (`vfx-flamenat.js` 가 같은 자리에서 같은 결론을 냈다 — 답은 값이 아니라
//  **어느 주기에 매다느냐**였다.)
const ZNPER = 2*Math.PI/1.15;               // 5.463639…초
/// 한 주기 안의 자리(초). ⚠️ `t` 가 음수여도 되게 두 번 접는다.
const ZNu = t => ((t%ZNPER)+ZNPER)%ZNPER;

// ── ⭐ 네 구간의 시각 — **사용자가 준 두 값이 축이다** ─────────────────────
//   1.50초(겹이 다 쌓이고 터질 때까지) · 2.00초(자염이 타는 시간) 둘 다 사용자.
//   나머지는 그 둘을 주기에 앉히고 남은 자리다.
// ⚠️⚠️ **주기의 원점이 「쉼」 한가운데다.** 「팍!」은 정의상 갑작스러운 사건이라
//   그것을 `u=0` 에 두면 **이음매에서 튄다.** 원점을 조용한 자리에 두면
//   이음매의 모든 값이 0 이고, 사건은 전부 주기 **안쪽**에서 일어난다.
const ZNT0   = 0.90;                        // ① 줄기가 나가는 시각
const ZNZAP  = 0.18;                        // ① 줄기 수명 — 「팍!」
const ZNT1   = ZNT0+ZNZAP;                  // 1.08  겹이 쌓이기 시작
/// ⭐ **사용자가 준 값** — 「1.5초 뒤에 펑」.
const ZNFUSE = 1.50;
/// ⭐ 겹 상한 **셋**. 사용자의 「삑 삑 삑」이 셋이고, 도감 기폭 L2 가
/// 「**겹 상한 3**」이라 같은 수다.
/// ⚠️ **이 칸은 레벨 축을 안 연다.** 성장표를 그리는 칸이 아니라 「무엇이
///   일어나는가」를 그리는 칸이라 상한을 고정한다(엔진의 [mgNovaDetonate] 는
///   `CAP=[2,3,4,5,6][LV-1]` 로 자란다 — 이식할 때 그쪽을 따른다).
const ZNCAP  = 3;
/// ⭐⭐ 겹 **간격 0.375초** — 내가 지은 값이 아니라 [mgNovaDetonate] 의 규칙이다:
///   `STK = PER*.75/CAP` — 「**주기의 3/4 에 상한이 찬다**」.
///   여기 주기는 사용자가 준 1.50초이므로 `1.50×.75/3 = 0.375`.
/// ⇒ 겹은 **1.455 · 1.830 · 2.205** 에 앉고, 마지막 겹 뒤 **0.375초**를 꽉 찬
///   채로 있다가 터진다. 그 한 박자가 「곧 터진다」를 만든다.
/// ⚠️ **점점 빨라지지 않는다.** 가속은 카운트다운의 문법이고, 이것은 **겹이
///   쌓이는 리듬**이다 — 엔진에서도 겹은 일정 간격으로 얹힌다.
const ZNSTK  = ZNFUSE*.75/ZNCAP;            // 0.375
const ZNT2   = ZNT1+ZNFUSE;                 // 2.58  ③ 펑
/// 펑의 수명 — [mgNovaDetonate] 의 `st.bo = .5` 그대로다.
const ZNBOOM = 0.50;
/// ⭐ **사용자가 준 값** — 「2초 정도? **죽을 때까지면 밸런스 파괴니까**」.
/// ⚠️ 이 한 줄이 값의 근거 전부다. 지속을 늘리면 「불이 붙으면 죽는다」가 되어
///   기폭이 곧 처형이 된다 — 사용자가 그 이유로 2초를 못 박았다.
const ZNBURN = 2.00;
const ZNT3   = ZNT2+ZNBURN;                 // 4.58  불이 꺼진다
/// 여운이 **정확히 0 이 되는** 시각. ⚠️ 이음매보다 0.12초 앞이다 —
/// 그 0.12초 동안은 **아무것도 안 그린다.** 표식([pvMark])·불씨가 `t` 를 직접
/// 쓰는데 그 주파수(1.1·0.9·3.0 rad/s)는 이 주기에서 안 닫히므로, **알파가
/// 0 인 것으로 넘기지 않고 호출 자체를 없애** 이음매를 증명 가능하게 만든다.
const ZNEND  = ZNPER-0.12;                  // 5.343639…

// ── 사건의 오름 — 「팍」도 1ms 훑기에서 도약이 없어야 한다 ─────────────────
// ⚠️ 사람 눈에 20~45ms 는 **즉발**이다(60fps 로 1.3~2.7프레임). 그 안에서
//   [ZNs3] 로 올리면 「팍」은 그대로인데 **미분이 유한**해진다.
