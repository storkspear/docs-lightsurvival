//   ⇒ 색만 맞추고 **그림을 제가 새로 짠 것**이 틀렸다. 실측이 그것을 말했다:
//       $ grep -c "PKflameEnv" docs/vfx/vfx-numb.js   →  **0건**
// ⇒ ⭐ **지금은 자염의 정본을 부른다.** 정본은 `vfx.js`(:50149) 의 한 줄이다:
//       PKflameCViol = PKfc("viol")
//         PKfc = k => ((c,t,dt,W,H,st)=>PKflameEnv(c,t,dt,W,H,st,"ess",.15,k))
//   ⇒ [PKflameEnv](…, `"ess"`, `.15`, `"viol"`) **한 줄이 자염이다.** ④ 가 그것을
//     인자까지 같은 값으로 부른다(아래 [ZNplume]). ⇒ 제트 · S자 봉투 · 덩어리 ·
