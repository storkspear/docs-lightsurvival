  const hit = Array.prototype.slice.call(H.children || []).filter((e) => {
    const nm = e.querySelector && e.querySelector(".cap .nm");
    return !!nm && (nm.textContent || "").trim() === title;
  })[0];
  if (!hit) return 0;
  const cv = hit.querySelector("canvas");
  if (!cv || !cv.__a) return 0;
  cv.__a.fn = function FLXgrid(c, t, dt, W, H2, st) {
    const sl = LV; LV = 5;
    try { FLXflame(c, t, dt, W, H2, st); } finally { LV = sl; }
  };
