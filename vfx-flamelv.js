/// **이미 서 있는 성장표 줄을 제자리에서 갈아 끼운다.**
///
/// ⚠️ [lvTable] 은 줄을 만들 때 `const fn=reg[key]` 로 **함수를 그 자리에서
///   붙잡는다.** 그래서 `vfx.js` 안에서 이미 그려진 줄은 뒤에서 `FX.FLconeA` 를
///   갈아도 **안 따라온다** — 그 줄만 헐고 다시 세운다.
/// ⚠️ **제자리에 넣는다.** 뒤에 덧붙이면 도감 차례가 흐트러진다.
/// ⚠️ 캐릭터 장에서는 이 함수가 **아무 일도 안 한다** — 그 장의 줄은
///   `mockup-char-fire.js` 가 **이 파일 뒤에** 세운다.
/// ⭐ **칸을 키운다** — 이 줄만 `grid-column:1/-1` 로 한 줄을 통째로 쓰고
///   `--blockmax` 를 올린다. 칸이 **139 → ~283px** 로 두 배가 된다.
/// ⚠️⚠️ **2열로 접히는 것과는 다른 이야기다** — 칸이 몇 열인지는 `--n`(늘 5)이
///   정한다. 접히는 자리는 `@media(max-width:640px)` 하나뿐이다(폰).
/// ⚠️ `flex` 로 전폭을 만들면 안 된다 — `mockup_lint.js` 검사 ④ 가 잡는다.
function FLXrelay(hostId, title) {
  const H = document.getElementById(hostId);
  if (!H) return 0;
  const W = H.__lv || H;
  const old = Array.prototype.slice.call(W.children || []).filter((e) => {
    if (!e.classList || !e.classList.contains("lvblock")) return false;
    const b = e.querySelector && e.querySelector(".hd b");
    return !!b && (b.textContent || "").trim() === title;
  })[0];
  if (!old) return 0;
  const at = old.nextSibling;
  const made = lvTable({
    host: W, rows: [FLXROW], reg: FX, cell: FLXCELL, name: "FLXcell",
    hostOf: () => W,
  });
  // ⚠️⚠️ **새 줄이 안 서면 헌 줄을 안 헌다.** 먼저 지우고 뒤에 세우면, 세우는
  //   쪽이 조용히 0 을 돌려주는 날 **화염방사가 화면에서 통째로 사라진다**.
  if (!made || !W.lastElementChild || W.lastElementChild === old) return 0;
  const row = W.lastElementChild;
  row.style.gridColumn = "1 / -1";
  row.style.setProperty("--blockmax", "none");
  W.insertBefore(row, at);
  // 헌 칸의 캔버스는 **그리기를 멈춘다.**
  Array.prototype.forEach.call(old.querySelectorAll("canvas"), (cv) => {
    if (cv.__a) cv.__a.fn = function FLXdead() {};
  });
  old.remove();
  return made;
}

/// **낱칸 하나의 그림만 갈아 끼운다** — 「기존 화염방사 폐기」(머리 ⑦).
