// ⚠️ `vfx.js` 의 스킬 문양을 안 빌린다 — 그건 **이미 있는 스킬**의 그림이고,
//   여기 있는 것은 아직 없는 것의 **제안**이다. 섞으면 「있는 것」으로 읽힌다.
// ⚠️ 알파 인자는 **선택**이다 — 안 주면 1. 앞 두 절이 `spRay`·`spBolt` 를
//   알파 없이 쓰고 있어 그 둘의 자리는 그대로 뒀다.

function spBlob(c, x, y, r, k, a) {
  c.fillStyle = A(k, a); c.beginPath(); c.arc(x, y, r, 0, TAU); c.fill();
}
function spDot(c, x, y, r, k, a) { spBlob(c, x, y, r, k, a == null ? 1 : a); }
function spRing(c, x, y, r, w, k, a) {
  c.strokeStyle = A(k, a); c.lineWidth = w;
  c.beginPath(); c.arc(x, y, r, 0, TAU); c.stroke();
}
function spArc(c, x, y, r, a0, a1, w, k, a) {
  c.strokeStyle = A(k, a); c.lineWidth = w; c.lineCap = "round";
  c.beginPath(); c.arc(x, y, r, a0, a1); c.stroke();
}
function spRay(c, x0, y0, x1, y1, w, k) {
  c.strokeStyle = k; c.lineWidth = w; c.lineCap = "round";
  c.beginPath(); c.moveTo(x0, y0); c.lineTo(x1, y1); c.stroke();
}
function spBolt(c, x0, y0, x1, y1, w, k) {
  const mx = (x0 + x1) / 2 + (y1 - y0) * .18, my = (y0 + y1) / 2 - (x1 - x0) * .18;
  c.strokeStyle = k; c.lineWidth = w; c.lineCap = "round"; c.lineJoin = "round";
  c.beginPath(); c.moveTo(x0, y0); c.lineTo(mx, my); c.lineTo(x1, y1); c.stroke();
}
function spFang(c, x, y, len, w, tilt) {
  c.save(); c.translate(x, y); c.rotate(tilt);
  c.fillStyle = "#4A3A6E";
  c.beginPath(); c.moveTo(0, -w); c.lineTo(len, 0); c.lineTo(0, w); c.closePath(); c.fill();
  c.fillStyle = A("#B79BFF", .8);
  c.beginPath(); c.moveTo(len * .5, -w * .3); c.lineTo(len, 0); c.lineTo(len * .5, w * .3);
  c.closePath(); c.fill();
  c.restore();
}
function spStar(c, x, y, r, k) {
  c.fillStyle = k; c.beginPath();
  for (let i = 0; i < 8; i++) {
    const a = i / 8 * TAU, rr = i % 2 ? r * .38 : r;
    const px = x + Math.cos(a) * rr, py = y + Math.sin(a) * rr;
    i ? c.lineTo(px, py) : c.moveTo(px, py);
  }
  c.closePath(); c.fill();
}
function spEye(c, x, y, r, k) {
  c.strokeStyle = k; c.lineWidth = 1.8; c.lineCap = "round";
  c.beginPath();
  c.moveTo(x - r, y); c.quadraticCurveTo(x, y - r * .74, x + r, y);
  c.quadraticCurveTo(x, y + r * .74, x - r, y);
  c.stroke();
  spBlob(c, x, y, r * .26, "#B79BFF", .95);
}

