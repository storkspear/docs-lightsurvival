/// `why` 안의 `**굵게**` 를 태그로 바꾼다.
///
/// ⚠️⚠️ **화면에 별표가 그대로 떴다**(2026-08-28 발견). `why` 는 처음부터
///   `**…**` 로 적혀 있었는데 문자열을 그대로 꽂아 넣어, 굵어지는 대신
///   「\*\*못 나가지는 않습니다.\*\*」가 읽혔다. ⇒ **문자열을 안 고치고 여기서
///   푼다** — 사용자가 보던 원문을 손대지 않는 쪽이 맞고, 새 절도 같은 문법으로
///   적을 수 있어 두 벌이 안 생긴다.
function spBold(s) { return s.replace(/\*\*(.+?)\*\*/g, "<b>$1</b>"); }

{
  const host = $("sp-body");
  if (host) {
    Object.entries(SPPICKS).forEach(([el, grp]) => {
      const filled = grp.have.length, need = SPSLOTS - filled;
      host.insertAdjacentHTML("beforeend",
        `<h2 id="s-${el}">${grp.nm} — 열두 칸 중 <b>${filled}</b> 참, `
        + `<b style="color:${SPSEL}">${need}</b> 비었습니다</h2>`
        + `<p class="sub">${spBold(grp.why)}</p>`
        + `<p class="sub">지금 있는 것: <b>${grp.have.join(" · ")}</b>`
        + ` &nbsp;·&nbsp; 이 절의 후보 <b style="color:${SPLINE}">${grp.picks.length}</b></p>`
        + `<div class="sp-grid" id="sp-${el}"></div>`);
      const g = $("sp-" + el);
      grp.picks.forEach(([id, nm, tag, one, draw]) => {
        const [tagNm, tagCol] = SPTAG[tag];
        const w = document.createElement("div");
        w.className = "sp-card";
        const cv = document.createElement("canvas");
        cv.className = "sp-art";
        w.appendChild(cv);
        w.insertAdjacentHTML("beforeend",
          `<div class="sp-nm">${nm}</div>`
          + `<div class="sp-tag" style="color:${tagCol};border-color:${tagCol}66">${tagNm}</div>`
          + `<div class="sp-one">${one}</div>`
          + `<div class="sp-id">${id}</div>`);
        g.appendChild(w);
        mk(cv, [72, 72], function spArt(c, t, dt, W, H) {
          c.clearRect(0, 0, W, H);
          draw(c, W);
        }, { clear: true });
      });
    });
  }
}
