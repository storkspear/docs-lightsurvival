// ⚠️ 앞 두 절이 원·고리·번개만으로 그려진 이유는 암과 뇌가 그런 속성이라서다.
//   나머지 다섯은 면과 결(빙) · 번짐(독) · 호(풍)라 그 조각으로는 안 그려진다.

/// 채운 다각형. `pts` 는 `[[x, y], …]`.
function spPoly(c, pts, k, a) {
  c.fillStyle = A(k, a == null ? 1 : a); c.beginPath();
  for (let i = 0; i < pts.length; i++) i ? c.lineTo(pts[i][0], pts[i][1]) : c.moveTo(pts[i][0], pts[i][1]);
  c.closePath(); c.fill();
}
/// 꺾인 선. 닫지 않는다 — 닫으려면 첫 점을 뒤에 한 번 더 넣는다.
function spLine(c, pts, w, k, a) {
  c.strokeStyle = A(k, a == null ? 1 : a); c.lineWidth = w;
  c.lineCap = "round"; c.lineJoin = "round"; c.beginPath();
  for (let i = 0; i < pts.length; i++) i ? c.lineTo(pts[i][0], pts[i][1]) : c.moveTo(pts[i][0], pts[i][1]);
  c.stroke();
}
/// 이차 곡선 한 도막.
function spCurve(c, x0, y0, cx, cy, x1, y1, w, k, a) {
  c.strokeStyle = A(k, a == null ? 1 : a); c.lineWidth = w; c.lineCap = "round";
  c.beginPath(); c.moveTo(x0, y0); c.quadraticCurveTo(cx, cy, x1, y1); c.stroke();
}
/// 가운데를 기준으로 한 사각 테두리.
function spBox(c, x, y, w, h, lw, k, a) {
  c.strokeStyle = A(k, a == null ? 1 : a); c.lineWidth = lw;
  c.strokeRect(x - w / 2, y - h / 2, w, h);
}
/// 물방울 — 위가 뾰족하고 아래가 둥글다.
function spDrop(c, x, y, r, k, a) {
  c.fillStyle = A(k, a == null ? 1 : a); c.beginPath();
  c.moveTo(x, y - r * 1.9);
  c.quadraticCurveTo(x + r * 1.05, y - r * .25, x + r * .86, y + r * .3);
  c.arc(x, y + r * .3, r * .86, 0, Math.PI);
  c.quadraticCurveTo(x - r * 1.05, y - r * .25, x, y - r * 1.9);
  c.closePath(); c.fill();
}
/// 잎 · 깃 — `(x, y)` 에서 `an` 쪽으로 `len` 만큼 뻗고 끝이 뾰족하다.
function spLeaf(c, x, y, len, wid, an, k, a) {
  c.save(); c.translate(x, y); c.rotate(an);
  c.fillStyle = A(k, a == null ? 1 : a); c.beginPath();
  c.moveTo(0, 0); c.quadraticCurveTo(len * .5, -wid, len, 0);
  c.quadraticCurveTo(len * .5, wid, 0, 0);
  c.closePath(); c.fill(); c.restore();
}
/// 가시 · 뿔 — `(x, y)` 에서 `an` 쪽으로 곧게 뻗은 삼각.
function spSpike(c, x, y, len, hw, an, k, a) {
  c.save(); c.translate(x, y); c.rotate(an);
  spPoly(c, [[len, 0], [0, -hw], [0, hw]], k, a);
  c.restore();
}
/// 물결 — `x0`~`x1` 사이에 산이 `n` 개. **위상 파생값을 안 그린다** — 한 식에서
/// 스물넷을 뽑으므로 양 끝이 저절로 맞는다.
function spWave(c, x0, x1, y, amp, n, w, k, a) {
  const pts = [];
  for (let i = 0; i <= 24; i++) {
    const t = i / 24;
    pts.push([x0 + (x1 - x0) * t, y + Math.sin(t * TAU * n) * amp]);
  }
  spLine(c, pts, w, k, a);
}
// ── 누운 것 — 장판이 쓰는 셋 ───────────────────────────────────────────────
// ⚠️ 셋 다 세로를 [SPFOLD] 만큼 누른다. **원을 그리는 `spBlob`·`spRing` 과 짝을
//   이루는 물건**이고, 어느 쪽을 쓰느냐가 곧 「이것이 서 있나 누워 있나」다.

/// 누운 면 — 바닥에 깔린 판.
function spDisc(c, x, y, r, k, a) {
  c.fillStyle = A(k, a == null ? 1 : a);
  c.beginPath(); c.ellipse(x, y, r, r * SPFOLD, 0, 0, TAU); c.fill();
}
/// 누운 테두리.
function spOval(c, x, y, r, w, k, a) {
  c.strokeStyle = A(k, a == null ? 1 : a); c.lineWidth = w;
  c.beginPath(); c.ellipse(x, y, r, r * SPFOLD, 0, 0, TAU); c.stroke();
}
/// 누운 테두리의 한 도막 — 끊어 그리면 「깜빡인다」가 정지 화면에서 읽힌다.
function spOvalArc(c, x, y, r, a0, a1, w, k, a) {
  c.strokeStyle = A(k, a == null ? 1 : a); c.lineWidth = w; c.lineCap = "round";
  c.beginPath(); c.ellipse(x, y, r, r * SPFOLD, 0, a0, a1); c.stroke();
}

/// 나선 — `r0`에서 `r1`까지 `turns` 바퀴.
function spSpiral(c, x, y, r0, r1, a0, turns, w, k, a) {
  const pts = [];
  for (let i = 0; i <= 48; i++) {
    const t = i / 48, an = a0 + t * TAU * turns, r = r0 + (r1 - r0) * t;
    pts.push([x + Math.cos(an) * r, y + Math.sin(an) * r]);
  }
  spLine(c, pts, w, k, a);
}

